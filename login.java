    private void btnloginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnloginActionPerformed
        // get user input from the text fields
        String chosenId = tfielduserid.getText().trim();
        String chosenPswd = new String(pfieldpassword.getPassword()).trim();
        String filepath = "users.txt";
        String holdUserDataPath = "holduserdata.txt"; // File to store logged-in user details

        ArrayList<users> userList = null;
        try 
        {
            userList = dataloader.loadusers(filepath);  // Ensure users.txt is in the correct location
        } 
        
        catch (IOException e) 
        {
        // Handle file load error (e.g., show a message and return)
        JOptionPane.showMessageDialog(this, "Error loading users: " + e.getMessage());
        return;
        }
        
        // Call the login function to validate the credentials
        users loggedInUser = users.login(chosenId, chosenPswd, userList);

        if (loggedInUser != null) 
        {
            
            // Write user data to holduserdata.txt (overwrite mode)
            try (FileWriter writer = new FileWriter(holdUserDataPath, false)) { // false = overwrite mode
                String userId = loggedInUser.getUser_id();
                String userName = loggedInUser.getUser_name();
                String role = "";

                // Determine role based on user ID
                if (userId.endsWith("v")) {
                    role = "vendor";
                } else if (userId.startsWith("a")) {
                    role = "admin";
                } else if (userId.startsWith("c")) {
                    role = "customer";
                } else if (userId.startsWith("m")) {
                    role = "manager";
                } else if (userId.startsWith("r")) {
                    role = "runner";
                } else {
                    role = "unknown"; // Default role if no match is found
                }

                // Write formatted data
                writer.write(userId + "," + userName + "," + role + "\n");

            } catch (IOException e) {
                JOptionPane.showMessageDialog(this, "Error writing user data: " + e.getMessage());
            }
            
            ////
            
            // Login successful, show a welcome message or navigate to another screen
            JOptionPane.showMessageDialog(this, "Login successful! Welcome, " + loggedInUser.getUser_name());
            char firstChar = chosenId.charAt(0);
            char lastChar = chosenId.charAt(chosenId.length()-1);
            
            // lead to admin
            if (firstChar == 'a') {
                new admin_main().setVisible(true);
            }
            // lead to manager
            else if (firstChar == 'm') {
                new ManagerDashboard().setVisible(true);
            }
            // lead to customer
            else if (firstChar == 'c'){
                new customer().setVisible(true);
            }
            // lead to vendor
            else if (lastChar == 'v'){
                new vendor_main().setVisible(true);
            }
            // lead to runner
            else if (firstChar == 'r'){
                new DeliveryRunner().setVisible(true);
            }
            
        } 
        else 
        {
            // Login failed, show an error message
            JOptionPane.showMessageDialog(this, "Invalid credentials. Please try again.", "Login Failed", JOptionPane.ERROR_MESSAGE);
        }
        
    }//GEN-LAST:event_btnloginActionPerformed

