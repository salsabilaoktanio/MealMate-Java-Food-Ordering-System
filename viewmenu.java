    private void btnviewActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnviewActionPerformed
        try {
        ArrayList<menu> menu_items = dataloader.loadmenuitems("themenu.txt");
        ArrayList<menu> filtered_menu_items = new ArrayList<>();
        
        for (menu item : menu_items) {
            if (item.getVendor_name().equalsIgnoreCase(selected_vendor)) {
                filtered_menu_items.add(item);                
            }
        }
        
        updateTable(filtered_menu_items);
        
    } catch (IOException e) {
        System.out.println("Error");
    }
    }//GEN-LAST:event_btnviewActionPerformed

