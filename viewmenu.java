    private void updateTable(ArrayList<menu> menu_items) {
        DefaultTableModel model = (DefaultTableModel) tblviewmenu.getModel();
        model.setRowCount(0);
        for (menu item : menu_items) {
            model.addRow(new Object[] {item.getVendor_id(), item.getVendor_name(), item.getItem_id(), item.getItem_name(), item.getItem_price()});
        }
    }
    
    
