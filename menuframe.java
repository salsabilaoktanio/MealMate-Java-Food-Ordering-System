    private void btnpayActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnpayActionPerformed
        //attributes
        address = txtaddress.getText().trim();
        
        //loading users        
        try{
            helduserlist = dataloader.loadheldusers("holduserdata.txt");                        
            for (holduserdata heldusers : helduserlist)
            {
                user_id = heldusers.getUserId();
            }
        }catch (IOException ex) {
            ex.printStackTrace();
        }
        
        //calculate time and date
        String time = order.writerealtime() +" "+ order.writerealdate();
        
        //get last balance
        double previous_balance = order.getLastUserBalance("wallet.txt", user_id);
        
        //verification
        System.out.println("Last balance for user " + user_id + ": " + previous_balance);
        System.out.println(previous_balance);
        
        //status initializations        
        String order_status = "Placed";
        
        //order & transaction ID
        String order_id = order.generateOrderID();
        String transaction_id = order.generatetransactionID();
        
        //attribute
        String vendor_name = selected_vendor; 
        
        //get item price
        String transaction_type = "deducted";
        for (menu item : menu_items)
        {
            if (item.getItem_name().equals(selected_item))
            {
                item_price = item.getItem_price();
            }
        }
        
        if (selected_item != null && !selected_item.isEmpty()) {
        for (menu item : menu_items) {
            if (item.getItem_name().equals(selected_item)) {
                total_charge = order.CalculateTotalPrice(item.getItem_price(), selected_option);
                break;
            }
        }
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Please select an item before proceeding.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        //total charge and current balance calculation
        double order_amount = total_charge; 
        double current_balance = previous_balance - order_amount; 
        
        
        if (previous_balance >= order_amount) {        
            //writing it customer_order_history.txt
            customer_order_history.writeintocustomerhistory(order_id, selected_item, user_id, time, order_amount, current_balance, address, selected_option, selected_vendor, order_status);
            
            //writing into order.txt
            order.writeorder("order.txt", order_id, user_id, selected_vendor, selected_item, item_price, selected_option, order_status, total_charge, time, address);
            //writing into vendor_history.txt
            order.writeorder("vendor_order_history.txt", order_id, user_id, selected_vendor, selected_item, item_price, selected_option, order_status, total_charge, time, address);
            
            //writing into wallet.txt
            wallet.writeransaction(user_id, total_charge, transaction_id, transaction_type, current_balance, order_id);
        
            javax.swing.JOptionPane.showMessageDialog(this, "Order placed successfully!\nOrder ID:" + order_id);
        } else {        
            javax.swing.JOptionPane.showMessageDialog(this, "Insufficient balance, please top up!", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }                        
    }//GEN-LAST:event_btnpayActionPerformed

