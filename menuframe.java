    private void updateTable(ArrayList<menu> menu_items) {
        DefaultTableModel model = (DefaultTableModel) tblmenu.getModel();
        model.setRowCount(0);
        for (menu item : menu_items) {
            double total_charge = order.CalculateTotalPrice(item.getItem_price(), selected_option);
            model.addRow(new Object[] {item.getVendor_id(), item.getItem_id(), item.getItem_name(), item.getItem_price(), selected_option, total_charge});
        }
    }
    
    
    
    
    
    
    
    
