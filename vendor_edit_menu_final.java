    // CREATER
    private void btn_createActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_createActionPerformed
        // retrieve input from text fields
        String vendorId = tf_vendorid.getText().trim();
        String vendorName = tf_vendorname.getText().trim();
        String itemId = tf_itemid.getText().trim();
        String itemName = tf_itemname.getText().trim();
        String itemPriceText = tf_itemprice.getText().trim();
        String menuFile = "themenu.txt";
        
        // validate so that every field is not empty
        if (vendorId.isEmpty() || vendorName.isEmpty() || itemId.isEmpty() || itemName.isEmpty() || itemPriceText.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "All fields are required.", "Input Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        // now this checks if the item id already exists in the text file or no
        try 
        {
            ArrayList<menu> menuList = dataloader.loadmenuitems(menuFile);
            for (menu item : menuList) 
            {
                if (item.getItem_id().equals(itemId)) 
                {
                    javax.swing.JOptionPane.showMessageDialog(this, "Item ID already exists. Please use a different ID.", "Input Error", JOptionPane.ERROR_MESSAGE);
                
                    // Clear the text fields
                    tf_vendorid.setText("");
                    tf_vendorname.setText("");
                    tf_itemid.setText("");
                    tf_itemname.setText("");
                    tf_itemprice.setText("");
                
                    return;
                }
            }
        } 
        catch (IOException e) 
        {
            javax.swing.JOptionPane.showMessageDialog(this, "Error reading the file: " + e.getMessage(), "File Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        // set itemPriceText as double
        double itemPrice;
        try 
        {
            itemPrice = Double.parseDouble(itemPriceText);
        }
        catch (NumberFormatException e)
        {
            javax.swing.JOptionPane.showMessageDialog(this, "Invalid price. Please enter a valid number.", "Input Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        // create menu entry string
        String menuEntry = String.join(",", vendorId, vendorName, itemId, itemName, String.valueOf(itemPrice));
        
        
        // write to file
        try (BufferedWriter writer = new BufferedWriter(new FileWriter(menuFile, true))) 
        {
            writer.newLine(); // Add a new line for the new entry
            writer.write(menuEntry);

            javax.swing.JOptionPane.showMessageDialog(this, "Menu item created successfully.", "Success", JOptionPane.INFORMATION_MESSAGE);

            // Optionally clear the text fields
            tf_vendorid.setText("");
            tf_vendorname.setText("");
            tf_itemid.setText("");
            tf_itemname.setText("");
            tf_itemprice.setText("");

        } 
        catch (IOException e) 
        {
            javax.swing.JOptionPane.showMessageDialog(this, "Error writing to file: " + e.getMessage(), "File Error", JOptionPane.ERROR_MESSAGE);
        }    
        
        
    }//GEN-LAST:event_btn_createActionPerformed

    // READ
    private void btn_readActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_readActionPerformed
        // To read
        String vendorId = tf_vendorid.getText().trim();
        
        // ensure the vendor id text field isnt empty
        if (vendorId.isEmpty())
        {
            javax.swing.JOptionPane.showMessageDialog(this, "Vendor ID is required.", "Input Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }
        // the list to store matching menu items
        ArrayList<String> matchingItems = new ArrayList<>();
        
        try (BufferedReader br = new BufferedReader (new FileReader("themenu.txt")))
        {
            String line;
            while ((line = br.readLine()) != null)
            {
                String[] parts = line.split(",");
                if (parts.length == 5 && parts[0].equals(vendorId))
                {
                    matchingItems.add(line);
                }
            }
            
            if (matchingItems.isEmpty())
            {    
                javax.swing.JOptionPane.showMessageDialog(this, "No items found for the given vendor ID.", "No Results", javax.swing.JOptionPane.INFORMATION_MESSAGE);        
            }
            
            else 
            {
                StringBuilder result = new StringBuilder("Menu items for vendor ID: " + vendorId + "\n");
                for (String item : matchingItems) 
                {
                    result.append(item).append("\n");
                }
                javax.swing.JOptionPane.showMessageDialog(this, result.toString(), "Results", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            }
            
        }
        catch (IOException e)
        {
            javax.swing.JOptionPane.showMessageDialog(this, "Error reading the file: " + e.getMessage(), "File Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btn_readActionPerformed

    // TO UPDATE
    private void btn_updateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_updateActionPerformed
        String itemId = tf_itemid.getText().trim();
        String vendorId = tf_vendorid.getText().trim();
        String newItemName = tf_itemname.getText().trim();
        String itemPriceText = tf_itemprice.getText().trim();
        
        // make sure item id and vendor id isnt empty
        if (itemId.isEmpty() || vendorId.isEmpty()) 
        {
            JOptionPane.showMessageDialog(this, "Item ID and Vendor ID are required.", "Input Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        // make itemprice into a double
        Double newItemPrice = null;
        if (!itemPriceText.isEmpty())
        {
            try 
            {
                newItemPrice = Double.parseDouble(itemPriceText);
            }
            catch (NumberFormatException e)
            {
                JOptionPane.showMessageDialog(this, "Invalid price. Please enter a valid number.", "Input Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
        }
        
        // try to load menu items from the file
        try 
        {
            ArrayList<menu> menuList = dataloader.loadmenuitems("themenu.txt");
            boolean itemFound = false;
            
            for (menu item : menuList)
            {
                if (item.getVendor_id().equals(vendorId) && item.getItem_id().equals(itemId))
                {
                    // update only the fields that have user input
                    if (newItemName != null && !newItemName.isEmpty())
                    {
                        item.setItem_name(newItemName);
                    }
                    
                    // 
                    if (newItemPrice != null ) 
                    {
                        item.setItem_price(newItemPrice);
                    }
                    itemFound = true;
                    break;
                }    
            }
            
            if (itemFound)
            {
                try (BufferedWriter writer = new BufferedWriter(new FileWriter("themenu.txt")))
                {
                    for (menu item : menuList)
                    {
                        writer.write(item.getVendor_id() + "," + 
                                 item.getVendor_name() + "," + 
                                 item.getItem_id() + "," + 
                                 item.getItem_name() + "," + 
                                 item.getItem_price());
                        writer.newLine();
                    }
                }
                JOptionPane.showMessageDialog(this, "Menu item updated successfully.", "Success", JOptionPane.INFORMATION_MESSAGE);
            }
            
            else 
            {
                 JOptionPane.showMessageDialog(this, "Item ID or Vendor ID not found.", "Error", JOptionPane.ERROR_MESSAGE);   
            }
            
        }
        
        catch (IOException e)
        {
            JOptionPane.showMessageDialog(this, "Error reading or writing to the file: " + e.getMessage(), "File Error", JOptionPane.ERROR_MESSAGE);    
        }
        
    }//GEN-LAST:event_btn_updateActionPerformed

    // DELETE ITEM
    private void btn_deleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_deleteActionPerformed
        String itemId = tf_itemid.getText().trim();
        String vendorId = tf_vendorid.getText().trim();
        
        // make sure item id and vendor id isnt empty
        if (itemId.isEmpty() || vendorId.isEmpty())
        {
            JOptionPane.showMessageDialog(this, "Both Item ID and Vendor ID are required.", "Input Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        // load menu items from the file
        try 
        {
            ArrayList <menu> menuList = dataloader.loadmenuitems("themenu.txt");
            boolean itemFound = false;
            
            // create a list to store items that are not deleted
            ArrayList <menu> updatedMenuList = new ArrayList<>();
            
            // iterate through the menu list and add items that dont match the item id 
            for (menu item : menuList)
            {
                if (!(item.getItem_id().equals(itemId)))
                {
                    updatedMenuList.add(item); // if item id doesnt match the inputted item id the update the list
                }
                else
                {
                    itemFound = true; // if item is found and deleted
                }
            }
            
            // if item was found and deleted, re write the updated list back to the file
            if (itemFound)
            {
                try (BufferedWriter writer = new BufferedWriter(new FileWriter("themenu.txt")))
                {
                    for (menu item : updatedMenuList)
                    {
                        writer.write(item.getVendor_id() + "," + 
                                 item.getVendor_name() + "," + 
                                 item.getItem_id() + "," + 
                                 item.getItem_name() + "," + 
                                 item.getItem_price());
                        writer.newLine();
                    }
                }
                
                JOptionPane.showMessageDialog(this, "Menu item deleted successfully.", "Success", JOptionPane.INFORMATION_MESSAGE);
    
            }
            else 
            {
                JOptionPane.showMessageDialog(this, "Item ID not found.", "Error", JOptionPane.ERROR_MESSAGE);    
            }
            
        }
        catch (IOException e)
        {
            JOptionPane.showMessageDialog(this, "Error reading or writing to the file: " + e.getMessage(), "File Error", JOptionPane.ERROR_MESSAGE);
        }
        
    }//GEN-LAST:event_btn_deleteActionPerformed

