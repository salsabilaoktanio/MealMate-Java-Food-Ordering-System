private void showCompletedTasks() {
    try {
        // Read the file from the 'data' package
        File file = new File("tasks.txt");
        BufferedReader reader = new BufferedReader(new FileReader(file));
        String line;
        DefaultTableModel model = (DefaultTableModel) taskHistoryTable.getModel(); // Get table model

        // Clear any existing data in the table
        model.setRowCount(0);

        // Read the file line by line
        while ((line = reader.readLine()) != null) {
            // Split each line by comma (assuming CSV format)
            String[] taskData = line.split(",");

            // Check if the task status is "completed"
            String taskStatus = taskData[4].trim();  // Assuming task status is at index 4
            if (taskStatus.equalsIgnoreCase("completed")) {
                // Add the task data to the table if the status is "completed"
                model.addRow(taskData);
            }
        }
        reader.close();
    } catch (IOException e) {
        JOptionPane.showMessageDialog(this, "Error reading tasks file: " + e.getMessage());
    }
}

