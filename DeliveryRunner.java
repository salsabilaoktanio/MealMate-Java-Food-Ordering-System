    private void tasksButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_tasksButtonActionPerformed
    
        viewTasks.setSelectedIndex(0);
    String filePath = "tasks.txt"; // Adjust the path if necessary
    List<String[]> newTaskList = new ArrayList<>();
    List<String[]> currentTaskList = new ArrayList<>();
    
    try (BufferedReader br = new BufferedReader(new FileReader(filePath))) {
        String line;
        while ((line = br.readLine()) != null) {
            String[] taskDetails = line.split(","); // Assuming the file uses commas as separators
            if (taskDetails.length > 4) {
                String status = taskDetails[4].trim().toLowerCase();
                
                // Filter for "runner requested" status
                if ("runner requested".equals(status)) {
                    newTaskList.add(taskDetails);
                }
                
                // Filter for "accepted", "ready to pick up", and "picked up" statuses
                if ("accepted".equals(status) || "ready to pick up".equals(status) || "picked up".equals(status)) {
                    currentTaskList.add(taskDetails);
                }
            }
        }
    } catch (IOException e) {
        JOptionPane.showMessageDialog(this, "Error reading the file: " + e.getMessage());
    }
    
    // Update both tables
    updateTable(newTaskList, newTasksTable);
    updateTable(currentTaskList, currentTasksTable);


    }//GEN-LAST:event_tasksButtonActionPerformed

