private void updateTable(List<String[]> taskList, JTable table) {
    // Define column headers
    String[] columnNames = {"Task ID", "Order ID", "User ID", "Address", "Status", "Earning", "Date"};
    
    // Convert List to 2D Array for the Table Model
    String[][] data = new String[taskList.size()][columnNames.length];
    for (int i = 0; i < taskList.size(); i++) {
        data[i] = taskList.get(i); // Populate each row
    }
    
    // Set the table model
    DefaultTableModel model = new DefaultTableModel(data, columnNames);
    table.setModel(model);
}


     // Method 2
private void updateTaskStatus(String taskId, String newStatus) {
    String filePath = "tasks.txt";
    List<String> updatedTasks = new ArrayList<>();

    try (BufferedReader br = new BufferedReader(new FileReader(filePath))) {
        String line;
        while ((line = br.readLine()) != null) {
            String[] taskDetails = line.split(",");
            if (taskDetails[0].equals(taskId)) {
                taskDetails[4] = newStatus; // Update the status
            }
            updatedTasks.add(String.join(",", taskDetails));
        }
    } catch (IOException e) {
        JOptionPane.showMessageDialog(this, "Error reading the file: " + e.getMessage());
    }

    // Write updated tasks back to the file
    try (BufferedWriter bw = new BufferedWriter(new FileWriter(filePath))) {
        for (String task : updatedTasks) {
            bw.write(task);
            bw.newLine();
        }
    } catch (IOException e) {
        JOptionPane.showMessageDialog(this, "Error writing to the file: " + e.getMessage());
    }
}

