    private void updateTable(ArrayList<order> orders) {
        DefaultTableModel model = (DefaultTableModel) tblorder.getModel();
        model.setRowCount(0);
        for (order an_order : orders) {
            model.addRow(new Object[] {an_order.getOrder_id(), an_order.getUser_id(), an_order.getVendor_name(), an_order.getItem_name(), an_order.getOrder_type(), an_order.getOrder_status(), an_order.getTotal_bill(), an_order.getData_and_time(), an_order.getAddress() });
        }
    }
