    private void btndisplayActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btndisplayActionPerformed
        try {
        ArrayList<order> orders = dataloader.loadorder("order.txt");
        ArrayList<order> filtered_order_items = new ArrayList<>();
        
        for (order an_order : orders) {
            if (an_order.getVendor_name().equalsIgnoreCase(selected_vendor)){
                filtered_order_items.add(an_order);                
            }
        }
        
        updateTable(filtered_order_items);
        
    } catch (IOException e) {
        System.out.println("Error");
    }
    }//GEN-LAST:event_btndisplayActionPerformed

    private void btncancelActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btncancelActionPerformed
        //cancelling an order
        order.updateOrderStatus(order_id, "Cancelled");
        
        try
        {
            customerorderhistorylist = dataloader.loadcustomerorderhistory("the_customer_order_history.txt");
            for (customer_order_history order_history : customerorderhistorylist)
            {
                if (order_id.equals(order_history.getOrder_id()))
                {
                    total_bill = order_history.getOrder_amount();
                    customer_id = order_history.getUser_id();
                }
            }
            
            ArrayList<top_up> topuplist = new ArrayList<>();
        
            String topup_status = "Cancelled";
            
            top_up.writetopup(customer_id, topup_status, total_bill);
            javax.swing.JOptionPane.showMessageDialog(this, "Order cancelled succesfully");
            
        }catch (IOException ex) {
            ex.printStackTrace();
        }
        
    }//GEN-LAST:event_btncancelActionPerformed

