    private void displayReviews(String vendorName) {
    List<Object[]> reviews = new ArrayList<>();

    try {
        // Read from review.txt
        BufferedReader reader = new BufferedReader(new FileReader("review.txt"));
        String line;

        // Read the file line by line
        while ((line = reader.readLine()) != null) {
            String[] fields = line.split(",", -1); // Split by commas, include empty values

            // Check if the line contains the vendor name
            if (fields[3].equalsIgnoreCase(vendorName)) {  // Vendor Name is in the 4th column (index 3)
                // Add the relevant fields to the review list
                reviews.add(new Object[]{
                    fields[1],  // Order ID
                    fields[4],  // Vendor Review
                    fields[5],  // Runner Name
                    fields[6]   // Runner Review
                });
            }
        }
        reader.close();
    } catch (IOException e) {
        JOptionPane.showMessageDialog(null, "Error reading reviews: " + e.getMessage());
        return;
    }

    // Convert the list to a 2D array for the JTable
    Object[][] data = reviews.toArray(new Object[reviews.size()][]);

    // Set the table model with the retrieved data
    tableModel.setDataVector(data, new String[]{"Order ID", "Vendor Review", "Runner Name", "Runner Review"});
    }
